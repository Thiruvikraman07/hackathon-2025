def demo_matching():
    """Run matching demo following observability tutorial pattern"""

    print("\n" + "="*70)
    print("JOB-RESUME MATCHING - Production Demo")
    print("="*70)
    print("Following Tutorial 05 (Observability) structure")
    print("Features: LangSmith tracing, error handling, metrics tracking")
    print()

    # Check LangSmith
    if os.getenv('LANGSMITH_API_KEY'):
        print("✅ LangSmith tracing enabled")
        if not os.getenv('LANGSMITH_TRACING'):
            os.environ['LANGSMITH_TRACING'] = 'true'
        if not os.getenv('LANGSMITH_PROJECT'):
            os.environ['LANGSMITH_PROJECT'] = 'job-resume-matching'
    else:
        print("⚠️  LangSmith tracing disabled (no API key)")

    # Load job description
    job_desc_path = Path("track_a_iron_man/job_description_example.txt")
    if not job_desc_path.exists():
        print("\n❌ Job description not found!")
        print(f"   Expected: {job_desc_path.absolute()}")
        return

    with open(job_desc_path, 'r') as f:
        job_desc = f.read()

    print(f"📄 Loaded job description: {len(job_desc)} chars")

    # Load resume data
    resume_json_path = Path("track_a_iron_man/resume_extract.json")
    if not resume_json_path.exists():
        print("\n❌ Resume data not found!")
        print(f"   Expected: {resume_json_path.absolute()}")
        print("   Run resume_agent.py first to extract resume data")
        return

    with open(resume_json_path, 'r') as f:
        resume_data = json.load(f)

    print(f"📄 Loaded resume data: {len(json.dumps(resume_data))} chars\n")

    # Run matching (single run, as per tutorial pattern)
    try:
        score, metrics = match_job_resume(job_desc, resume_data, enable_tracing=True)

        print("Demo complete! Key takeaways:")
        print("  ✅ Single run (no unnecessary loops)")
        print("  ✅ LangSmith tracing for observability")
        print("  ✅ Simple schema (LLM-friendly)")
        print("  ✅ Comprehensive metrics tracking")
        print("  ✅ Proper error handling")

    except Exception as e:
        print(f"\n❌ Demo failed: {e}")
        print("\nThis demonstrates error handling - agent fails gracefully")


if __name__ == "__main__":
    demo_matching()
